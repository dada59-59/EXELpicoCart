/* test sur PC des manettes USB HID generiques (exlpad.h) : lecture des descripteurs de
 * rapport de manettes courantes, decodage de leurs rapports, et ce que l'emetteur
 * infrarouge en fait (ordonnanceur d'exlir.h, temps simule a la milliseconde).
 *   gcc -O2 -Wall -o test_pad test_pad.c && ./test_pad */
#include <stdio.h>
#include <string.h>
#include "exlir.h"
#include "exlpad.h"
kbd_state_t g_kbd;
pad_state_t g_pad;
static int fails = 0;
#define OK(c, ...) do { int ok_ = (c); printf("%s ", ok_ ? "OK   " : "ECHEC"); printf(__VA_ARGS__); printf("\n"); if (!ok_) fails++; } while (0)

/* manette "SNES USB" generique (DragonRise 0079:0011) : 5 octets d'axes (4 "X" puis
 * un "Y" ; la croix est sur les octets 3 et 4), un quartet sans usage, 10 boutons */
